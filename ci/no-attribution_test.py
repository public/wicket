#!/usr/bin/env python3
"""Tests for ci/no-attribution.py: run with `python3 -I ci/no-attribution_test.py`."""

import importlib.util
import pathlib
import unittest

spec = importlib.util.spec_from_file_location("na", pathlib.Path(__file__).with_name("no-attribution.py"))
na = importlib.util.module_from_spec(spec)
spec.loader.exec_module(na)


class Findings(unittest.TestCase):
    def refused(self, text):
        self.assertTrue(na.findings(text, "t"), text)

    def allowed(self, text):
        self.assertEqual(na.findings(text, "t"), [], text)

    def test_attribution_forms_are_refused(self):
        self.refused("feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
        self.refused("co-authored-by: Claude <x@example.com>")
        self.refused("Body\n\n_Generated by [Claude Code](https://claude.ai/code)_")
        self.refused("\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)")
        self.refused("Claude-Session: https://claude.ai/code/session_01ABC")
        self.refused("see https://claude.ai/code/session_01ABC for the run")
        self.refused("Co-authored-by: GitHub Copilot <copilot@github.com>")

    def test_naming_a_harness_is_fine(self):
        self.allowed("feat(session): Claude Code runs in the session view")
        self.allowed("fix(agent): the Claude adapter reads stream-json")
        self.allowed("Co-Authored-By: Alex Stapleton <alexs@example.com>")
        self.allowed("docs: generated with ci/gen-cli-reference.sh")


if __name__ == "__main__":
    unittest.main()
